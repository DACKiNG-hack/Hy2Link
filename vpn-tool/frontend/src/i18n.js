/** 根据系统 / 上次选择推断语言 */
export function detectLocale() {
    try {
        const saved = localStorage.getItem('hy2link_locale')
        if (saved && messages[saved]) return saved
    } catch (_) {}

    const nav = (
        (typeof navigator !== 'undefined' &&
            (navigator.language || navigator.userLanguage)) ||
        ''
    ).toLowerCase()

    if (nav.startsWith('zh-tw') || nav.startsWith('zh-hk') || nav.startsWith('zh-hant')) return 'zh-TW'
    if (nav.startsWith('zh')) return 'zh-CN'
    if (nav.startsWith('ja')) return 'ja-JP'
    if (nav.startsWith('en')) return 'en-US'
    return 'zh-CN'
}

/** 参数占位符替换：format('a {x}', {x: 1}) -> 'a 1' */
export function format(str, params) {
    if (!params) return str
    return String(str).replace(/\{(\w+)\}/g, (m, k) =>
        Object.prototype.hasOwnProperty.call(params, k) ? params[k] : m
    )
}